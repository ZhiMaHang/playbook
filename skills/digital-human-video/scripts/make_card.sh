#!/bin/bash
# 数据图卡生成(PIL 渲染,1080x1920 深底白字)
# 用法: make_card.sh <out.png> <标题> <正文行1|行2|行3> [脚注]
#
# ⚠️ 脚注默认为空,**不要再给它设内容相关的默认值**(2026-08-04 实测踩到):
# 这里原先默认「单一商户题集实测 · 不代表行业均值」——那是某一条监测片子的免责声明,
# 却被盖到了一张跟监测毫无关系的引流卡上。默认值是一句**具体的事实声明**,
# 出现在不适用的片子上就是在陈述一件不成立的事,比缺一行字严重得多。
# 而且当时用 ${4:-...},传空字符串也会触发默认,想去掉都去不掉。现改为 ${4-} 且默认空。
set -euo pipefail
DIR="$(cd "$(dirname "$0")" && pwd)"
python3 "$DIR/render_text.py" card "$1" "$2" "$3" "${4-}"
echo "图卡 → $1"
